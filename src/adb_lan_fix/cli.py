"""Command-line entry point: `adb-lan-fix <subcommand>` or `adb-lan-fix -s X <cmd>`.

Two modes:

  * Subcommands (`install`, `doctor`, `status`, `uninstall`) manage the daemon.
  * Anything else is treated as adb arguments and handed to the real adb with
    forwarding applied, so `adb-lan-fix -s 192.168.1.50:5555 shell ...` works.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

from . import paths, shim
from .net import is_loopback, is_private_ipv4, reachable, split_serial


def _print(message: str = "") -> None:
    print(message)


# --------------------------------------------------------------------------- #
# subcommands
# --------------------------------------------------------------------------- #
def cmd_install(args: argparse.Namespace) -> int:
    if not shim.is_supported_platform():
        _print(f"Nothing to do: this workaround is macOS-only (you are on {sys.platform}).")
        _print("On other platforms `adb` reaches LAN devices directly.")
        return 0

    try:
        real = shim.find_real_adb()
    except FileNotFoundError as exc:
        _print(f"error: {exc}")
        return 1

    _print(f"real adb : {real}")
    _print(f"node     : {shim.node_binary() or '(missing)'}")

    if not shim.node_binary():
        _print("\nerror: Node.js is required (the forwarder runs inside it).")
        _print("Install Node.js, then re-run `adb-lan-fix install`.")
        return 1

    ok = shim.ensure_daemon()
    if not ok:
        _print("\nerror: the daemon did not start. Check:")
        _print(f"  {paths.DAEMON_LOG}")
        _print(f"  {paths.STATE_DIR / 'launchd.err.log'}")
        return 1

    _print(f"daemon   : running (pid {shim._daemon_request({'op': 'ping'}).get('pid')})")
    _print(f"launchd  : {paths.LAUNCH_AGENT}")

    # Global launcher: makes a bare `adb` work in every project, with no
    # per-project setup. This is the whole point of the package.
    bin_dir = Path(args.bin_dir) if args.bin_dir else paths.LAUNCHER_DIR
    if args.no_launcher:
        _print("\nInstalled (daemon only). Devices are forwarded on first use.")
        return 0

    if not _install_launcher(bin_dir):
        return 1

    _report_path(bin_dir)
    return 0


def _install_launcher(bin_dir: Path) -> bool:
    """Write an `adb` launcher that shadows the real adb on PATH.

    Points at a dedicated virtualenv so the launcher keeps working even if the
    checkout it was installed from is moved or deleted.
    """
    try:
        bin_dir.mkdir(parents=True, exist_ok=True)
        interpreter = _stable_interpreter()
        launcher = bin_dir / "adb"
        launcher.write_text(
            "#!/bin/sh\n"
            "# Generated by adb-lan-fix -- do not edit.\n"
            "# Remove with: adb-lan-fix uninstall\n"
            f'exec "{interpreter}" -m adb_lan_fix.cli "$@"\n'
        )
        launcher.chmod(0o755)
        _print(f"launcher : {launcher}")
        return True
    except OSError as exc:
        _print(f"\nerror: could not write launcher to {bin_dir}: {exc}")
        return False


def _stable_interpreter() -> str:
    """Return a Python that can import this package and will outlive the checkout.

    When running from a virtualenv outside the source tree, that interpreter is
    already stable. When running from a dev install or a source checkout, build
    a dedicated venv under the state directory so the launcher does not depend on
    the checkout staying put.
    """
    current = Path(sys.executable).resolve()
    if paths.VENV_PYTHON.exists() and paths.VENV_PYTHON.resolve() == current:
        return str(current)

    # Already a venv outside the project? Use it as-is.
    if (current.parent.parent / "pyvenv.cfg").exists() and not str(current).startswith(
        str(paths.PROJECT_DIR)
    ):
        return str(current)

    if paths.VENV_PYTHON.exists():
        return str(paths.VENV_PYTHON)

    _print(f"venv     : creating {paths.VENV_DIR}")
    try:
        subprocess.run(
            [sys.executable, "-m", "venv", str(paths.VENV_DIR)],
            check=True,
            capture_output=True,
            timeout=180,
        )
        subprocess.run(
            [str(paths.VENV_PYTHON), "-m", "pip", "install", "-q", str(paths.PROJECT_DIR)],
            check=True,
            capture_output=True,
            timeout=300,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        _print(f"warning: could not build a dedicated venv ({exc}); using {current}")
        return str(current)
    return str(paths.VENV_PYTHON)


def _report_path(bin_dir: Path) -> None:
    """Tell the user whether the launcher will actually win on PATH."""
    entries = [Path(p) for p in os.environ.get("PATH", "").split(os.pathsep) if p]
    try:
        real = Path(shim.find_real_adb()).resolve()
    except FileNotFoundError:
        real = None

    launcher_index = None
    real_index = None
    for index, entry in enumerate(entries):
        try:
            resolved = entry.resolve()
        except OSError:
            continue
        if launcher_index is None and resolved == bin_dir.resolve():
            launcher_index = index
        if real_index is None and real is not None and resolved in {
            real.parent,
            real.parent.resolve(),
        }:
            real_index = index

    _print()
    if launcher_index is None:
        _print(f"action   : add {bin_dir} to PATH, before your adb directory:")
        _print(f'           export PATH="{bin_dir}:$PATH"')
        return
    if real_index is not None and real_index < launcher_index:
        _print(f"warning  : {entries[real_index]} comes before {bin_dir} on PATH,")
        _print("           so the real adb still wins. Move the launcher earlier:")
        _print(f'           export PATH="{bin_dir}:$PATH"')
        return
    _print("ready    : a bare `adb` now works in every project, no setup needed.")


def cmd_uninstall(args: argparse.Namespace) -> int:
    label = paths.LAUNCH_AGENT_LABEL
    uid = os.getuid()
    for cmd in (
        ["launchctl", "bootout", f"gui/{uid}/{label}"],
    ):
        try:
            subprocess.run(cmd, capture_output=True, timeout=15)
        except (OSError, subprocess.SubprocessError):
            pass

    removed = []
    for target in (paths.LAUNCH_AGENT, paths.LAUNCHER_DIR / "adb"):
        try:
            # Only remove a launcher this package wrote.
            if target.name == "adb":
                head = target.read_text()[:200]
                if "adb-lan-fix" not in head:
                    continue
            target.unlink()
            removed.append(str(target))
        except (OSError, UnicodeDecodeError):
            pass

    if not args.keep_state:
        try:
            shutil.rmtree(paths.STATE_DIR)
            removed.append(str(paths.STATE_DIR))
        except OSError:
            pass

    if removed:
        _print("Removed:")
        for item in removed:
            _print(f"  {item}")
    else:
        _print("Nothing to remove.")
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    _print(f"platform     : {sys.platform}")
    _print(f"supported    : {'yes' if shim.is_supported_platform() else 'no (pass-through)'}")
    _print(f"state dir    : {paths.STATE_DIR}")
    _print(f"launch agent : {paths.LAUNCH_AGENT} "
           f"({'present' if paths.LAUNCH_AGENT.exists() else 'absent'})")

    alive = shim.daemon_alive()
    _print(f"daemon       : {'running' if alive else 'not running'}")
    if alive:
        reply = shim._daemon_request({"op": "list"}) or {}
        devices = reply.get("devices") or {}
        if devices:
            _print("forwards     :")
            for key, port in sorted(devices.items()):
                host, _, port_str = key.rpartition(":")
                state = "up" if reachable("127.0.0.1", int(port), 0.4) else "DOWN"
                _print(f"  {key:<28} -> 127.0.0.1:{port}  [{state}]")
        else:
            _print("forwards     : none registered yet")
    return 0


def cmd_doctor(args: argparse.Namespace) -> int:
    try:
        real = shim.find_real_adb()
    except FileNotFoundError as exc:
        _print(f"error: {exc}")
        return 1

    _print(f"real adb     : {real}")
    _print(f"node         : {shim.node_binary() or '(missing)'}")
    _print(f"platform     : {sys.platform}")
    _print(f"state dir    : {paths.STATE_DIR}")
    _print(f"daemon       : {'running' if shim.daemon_alive() else 'not running'}")
    _print()

    try:
        listing = subprocess.run(
            [real, "devices"], capture_output=True, text=True, timeout=30
        ).stdout
    except (OSError, subprocess.SubprocessError) as exc:
        _print(f"`adb devices` failed: {exc}")
        return 1

    rows = [line.split() for line in listing.splitlines()[1:] if line.strip()]
    if not rows:
        _print("no devices reported by adb")
        _print("Connect a device first (USB or `adb-lan-fix connect <ip>:<port>`).")
        return 0

    problems = 0
    forwarded = 0
    for row in rows:
        serial = row[0]
        split = split_serial(serial)
        if not split:
            _print(f"{serial:<28} usb/local  ok")
            continue
        host, port = split
        if is_loopback(host):
            forwarded += 1
            _print(f"{serial:<28} forwarded  ok")
            continue
        if reachable(host, port):
            _print(f"{serial:<28} direct     ok")
            continue
        problems += 1
        _print(f"{serial:<28} direct     BLOCKED")
        try:
            fwd = shim.ensure_forward(host, port)
            _print(f"{'':<28} forward    ok -> 127.0.0.1:{fwd}")
        except (RuntimeError, FileNotFoundError) as exc:
            _print(f"{'':<28} forward    FAILED ({exc})")

    _print()
    if problems:
        _print(f"{problems} device(s) needed forwarding. The shim handles this automatically.")
        _print("See docs/ROOT_CAUSE.md for why macOS blocks the adb binary.")
    elif forwarded:
        _print(f"{forwarded} device(s) are already forwarded through loopback.")
    else:
        _print("All devices reachable directly; the shim is a no-op here.")
    return 0


def cmd_version(args: argparse.Namespace) -> int:
    from . import __version__

    _print(f"adb-lan-fix {__version__}")
    return 0


# --------------------------------------------------------------------------- #
# entry point
# --------------------------------------------------------------------------- #
def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)

    if not argv:
        _print(__doc__)
        return 0

    sub = argv[0]
    rest = argv[1:]

    if sub == "help":
        _print(__doc__)
        return 0

    if sub == "install":
        parser = argparse.ArgumentParser(prog="adb-lan-fix install")
        parser.add_argument(
            "--bin-dir",
            default=None,
            help=f"where to write the `adb` launcher (default: {paths.LAUNCHER_DIR})",
        )
        parser.add_argument(
            "--no-launcher",
            action="store_true",
            help="install the daemon only, without shadowing `adb` on PATH",
        )
        return cmd_install(parser.parse_args(rest))

    if sub == "uninstall":
        parser = argparse.ArgumentParser(prog="adb-lan-fix uninstall")
        parser.add_argument(
            "--keep-state",
            action="store_true",
            help="keep the device registry and logs",
        )
        return cmd_uninstall(parser.parse_args(rest))

    if sub == "doctor":
        return cmd_doctor(argparse.ArgumentParser(prog="adb-lan-fix doctor").parse_args(rest))

    if sub == "status":
        return cmd_status(argparse.ArgumentParser(prog="adb-lan-fix status").parse_args(rest))

    if sub == "version":
        return cmd_version(argparse.ArgumentParser(prog="adb-lan-fix version").parse_args(rest))

    # Anything else is adb arguments.
    return shim.exec_adb(argv)


if __name__ == "__main__":
    raise SystemExit(main())
